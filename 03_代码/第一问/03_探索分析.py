import pandas as pd
import matplotlib.pyplot as plt


# ============================================================
# 1. 读取上一阶段生成的清洗数据
# ============================================================

file_path = "02_数据/清洗数据/第一问_男胎清洗数据.csv"

df = pd.read_csv(file_path)


# ============================================================
# 2. 检查数据是否正常读入
# ============================================================

print("前5行关键数据：")

print(
    df[
        [
            "孕周_数值",
            "孕妇BMI",
            "Y染色体浓度"
        ]
    ].head()
)


# ============================================================
# 3. 探索：孕周与 Y 染色体浓度
# ============================================================

plt.scatter(
    df["孕周_数值"],
    df["Y染色体浓度"]
)

plt.xlabel("Gestational Week")
plt.ylabel("Y Chromosome Concentration")
plt.title("Gestational Week vs Y Chromosome Concentration")

plt.show()


# ============================================================
# 4. 探索：BMI 与 Y 染色体浓度
# ============================================================

plt.scatter(
    df["孕妇BMI"],
    df["Y染色体浓度"]
)

plt.xlabel("BMI")
plt.ylabel("Y Chromosome Concentration")
plt.title("BMI vs Y Chromosome Concentration")

plt.show()


# ============================================================
# 5. Pearson 相关性分析
# ============================================================

corr_week = df["孕周_数值"].corr(
    df["Y染色体浓度"]
)

corr_bmi = df["孕妇BMI"].corr(
    df["Y染色体浓度"]
)


# ============================================================
# 6. 输出相关系数
# ============================================================

print("\nPearson 相关系数：")

print(
    "孕周 vs Y染色体浓度：",
    corr_week
)

print(
    "BMI  vs Y染色体浓度：",
    corr_bmi
)